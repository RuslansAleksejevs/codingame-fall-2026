#!/usr/bin/env python3
"""Embed exact float32 weights as 15-bit Unicode data in one C++ source."""
import hashlib
import argparse
import json
from pathlib import Path
import struct

BASE = Path(__file__).resolve().parents[3]
parser = argparse.ArgumentParser()
parser.add_argument('--league', choices=['full', 'silver'], default='full')
args = parser.parse_args()
suffix = '-silver' if args.league == 'silver' else ''
selection = json.loads((BASE / 'code/rl/configs/selected-policy.json').read_text())
weights = BASE / selection['weights']
assert hashlib.sha256(weights.read_bytes()).hexdigest() == selection['weights_sha256']
tokens = weights.read_text().split()
assert tokens[0] == 'TRYANGLE_MLP_V1'
layers = int(tokens[1])
dims = list(map(int, tokens[2:3 + layers]))
values = list(map(float, tokens[3 + layers:]))
assert len(values) == sum((a + 1) * b for a, b in zip(dims, dims[1:])) == 24833
raw = struct.pack('<' + 'f' * len(values), *values)
symbols, accumulator, bits = [], 0, 0
for byte in raw:
    accumulator = (accumulator << 8) | byte
    bits += 8
    while bits >= 15:
        bits -= 15
        symbols.append(chr(0x4000 + ((accumulator >> bits) & 32767)))
    accumulator &= (1 << bits) - 1
if bits:
    symbols.append(chr(0x4000 + (accumulator << (15 - bits))))
payload = ',\n'.join('R"CGW(' + '\n'.join(''.join(symbols[i:i + 256]) for i in range(start, min(start + 12800, len(symbols)), 256)) + ')CGW"'
                     for start in range(0, len(symbols), 12800))
sim = (BASE / 'code/rl/sim/simulator.hpp').read_text().replace('#pragma once\n', '')
policy = (BASE / 'code/rl/models/policy.hpp').read_text().replace('#pragma once\n', '').replace('#include "../sim/simulator.hpp"\n', '')
inference = (BASE / 'code/rl/export/inference.hpp').read_text().replace('#pragma once\n', '').replace('#include "../models/policy.hpp"\n', '')
original = (BASE / 'code/rl/export/bot.cpp').read_text()
body = original[original.index('    rl::State s;'):].replace('net.act(s,0,style)', 'fast.act(s,0,style)')
loader = r'''
#include <cstdint>
#include <cstring>
#include <iostream>
#include <chrono>
// Opaque model data, not natural-language text. Exact original float32 bits.
static const char* packed_weights[] = {PAYLOAD};
std::vector<unsigned char> unpack_weights() {
    std::vector<unsigned char> data;
    data.reserve(BYTE_COUNT);
    uint32_t accumulator = 0; int bits = 0;
    for (const char* part : packed_weights) {
    const auto* p = reinterpret_cast<const unsigned char*>(part);
    while (*p) {
        if (*p == '\n' || *p == '\r') { ++p; continue; }
        if ((p[0] & 240) != 224 || (p[1] & 192) != 128 || (p[2] & 192) != 128)
            throw std::runtime_error("Invalid packed UTF-8");
        unsigned code = ((p[0] & 15) << 12) | ((p[1] & 63) << 6) | (p[2] & 63);
        p += 3;
        if (code < 0x4000 || code >= 0xc000) throw std::runtime_error("Invalid packed symbol");
        accumulator = (accumulator << 15) | (code - 0x4000); bits += 15;
        while (bits >= 8) {
            bits -= 8;
            if (data.size() < BYTE_COUNT) data.push_back((accumulator >> bits) & 255);
        }
        accumulator &= (1u << bits) - 1;
    }
    }
    if (data.size() != BYTE_COUNT) throw std::runtime_error("Truncated packed weights");
    return data;
}
void load_embedded(rl::Network& net) {
    auto data = unpack_weights(); size_t offset = 0;
    auto next = [&]() {
        uint32_t bits = 0;
        for (int j = 0; j < 4; ++j) bits |= uint32_t(data.at(offset++)) << (8 * j);
        float value; static_assert(sizeof(value) == 4); std::memcpy(&value, &bits, 4); return value;
    };
    net.dims = {DIMS};
    for (size_t layer = 0; layer + 1 < net.dims.size(); ++layer) {
        net.weights.emplace_back(net.dims[layer] * net.dims[layer + 1]);
        net.bias.emplace_back(net.dims[layer + 1]);
        for (float& value : net.weights.back()) value = next();
        for (float& value : net.bias.back()) value = next();
    }
    if (offset != data.size()) throw std::runtime_error("Unexpected weight count");
}
#ifdef TRYANGLE_PACK_CHECK
int main() { auto bytes = unpack_weights(); std::cout.write(reinterpret_cast<const char*>(bytes.data()), bytes.size()); }
#else
int main() {
    rl::Network net; load_embedded(net); rl::FastNetwork fast(net, MAX_ACTION_KIND); int style = 2;
'''.replace('PAYLOAD', payload).replace('BYTE_COUNT', str(len(raw))).replace('DIMS', ','.join(map(str, dims))).replace('MAX_ACTION_KIND', '4' if args.league == 'silver' else '6')
source = '// PPO v2 league3m. Generated by code/rl/export/package.py.\n'
source += '// Weight SHA256: ' + selection['weights_sha256'] + '\n'
source += '#if defined(__GNUC__) && !defined(__clang__)\n#pragma GCC optimize("O3")\n#endif\n'
source += sim + '\n' + policy + '\n' + inference + '\n' + loader + body + '\n#endif\n'
units = len(source.encode('utf-16-le')) // 2
assert units < 100000
target = BASE / f'submissions/ppo-v2-league3m{suffix}.cpp'
target.write_text(source)
out = BASE / 'experiments/rl/2026-11-06-live-ppo-v2'
out.mkdir(exist_ok=True, parents=True)
manifest = {'weights_sha256': selection['weights_sha256'], 'float32_sha256': hashlib.sha256(raw).hexdigest(),
            'source_sha256': hashlib.sha256(source.encode()).hexdigest(), 'float32_parameters': len(values),
            'float32_bytes': len(raw), 'packed_symbols': len(symbols), 'source_utf16_units': units,
            'source_utf8_bytes': len(source.encode()), 'encoding': '15-bit symbols U+4000..U+BFFF, exact IEEE-754 float32 data; no quantization',
            'policy_style': 2, 'dimensions': dims, 'external_files_required': False,
            'inference': 'Transposed weight layout, independent output SIMD, original per-neuron accumulation order'}
manifest['action_profile'] = args.league
manifest['maximum_action_kind'] = 4 if args.league == 'silver' else 6
(out / f'package{suffix}.json').write_text(json.dumps(manifest, indent=2) + '\n')
(BASE / 'code/build').mkdir(exist_ok=True, parents=True)
(BASE / 'code/build/ppo2-expected-float32.bin').write_bytes(raw)
print(json.dumps(manifest, indent=2))
